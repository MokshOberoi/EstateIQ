from pydantic import BaseModel, Field, validator
from typing import Literal
import uuid

class PredictRequest(BaseModel):
    """Request payload for lead prediction.

    The fields correspond to the numeric features used by the ML model.
    They must match the column names generated by the training script.
    """
    total_views: int = Field(..., ge=0, description="Total number of property views")
    total_favourites: int = Field(..., ge=0, description="Total number of times the user favourited properties")
    total_enquiries: int = Field(..., ge=0, description="Total number of enquiries made by the user")
    total_dwell_time: int = Field(..., ge=0, description="Total time (seconds) spent on property pages")
    engagement_score: float = Field(..., ge=0, description="Composite engagement score")
    recency_score: float = Field(..., ge=0, description="Score based on recent activity")
    intent_score: float = Field(..., ge=0, description="Score representing purchase intent")

    @validator('*')
    def non_negative(cls, v):
        if v < 0:
            raise ValueError('Value must be non‑negative')
        return v

class PredictResponse(BaseModel):
    classification: Literal["COLD", "WARM", "HOT"]
    confidence: float = Field(..., ge=0, le=1, description="Probability of the predicted class")
    probabilities: dict = Field(..., description="Probabilities for all classes")

